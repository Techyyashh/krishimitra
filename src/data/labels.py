def _clean(text: str) -> str:
    return " ".join(text.replace("_", " ").replace(" ,", ",").split()).strip()


def crop_key(label: str) -> str:
    """'Corn_(maize)___Common_rust_' -> 'Corn_(maize)' (the raw crop part of the label)."""
    return label.partition("___")[0]


def parse_label(label: str) -> tuple[str, str, bool]:
    """Split a class label into (crop, disease, is_healthy) in readable form.

    >>> parse_label("Pepper,_bell___Bacterial_spot")
    ('Pepper, bell', 'Bacterial spot', False)
    """
    crop_raw, _, disease_raw = label.partition("___")
    is_healthy = disease_raw.strip("_").lower() == "healthy"
    disease = "Healthy" if is_healthy else _clean(disease_raw)
    return _clean(crop_raw), disease, is_healthy
